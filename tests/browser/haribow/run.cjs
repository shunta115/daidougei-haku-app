const { webkit, chromium } = require(process.env.PLAYWRIGHT_MODULE || '/private/tmp/haku-live-browser-tools/node_modules/playwright')
const assert = require('node:assert/strict')
;(async () => {
 const results=[]
 for (const [name, engine] of [['chromium',chromium]]) {
  const browser=await engine.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'})
  const page=await browser.newPage({viewport:{width:390,height:844}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1' ? r.continue():r.abort())
  await page.goto('http://127.0.0.1:5189/tests/browser/haribow/index.html')
  await page.getByRole('button',{name:'タップしてLIVE音声を再生'}).click()
  assert.equal(await page.evaluate(()=>window.__hakuLiveQa.audioStarts),1)
  await page.evaluate(()=>window.__hakuLiveQa.emit('reconnecting'))
  await page.getByRole('status').filter({hasText:'再接続'}).waitFor()
  await page.evaluate(()=>window.__hakuLiveQa.emit('reconnected'))
  await page.evaluate(()=>window.__hakuLiveQa.emit('disconnected'))
  console.log('before-retry',await page.evaluate(()=>({connects:window.__hakuLiveQa.connects, disconnects:window.__hakuLiveQa.disconnects})))
  await page.getByRole('button',{name:'LIVEに再接続',exact:true}).click()
  console.log('after-retry',await page.evaluate(()=>({connects:window.__hakuLiveQa.connects, disconnects:window.__hakuLiveQa.disconnects})))
  await page.waitForFunction(()=>window.__hakuLiveQa.connects===2)
  await page.locator('.pl-live__stage').click({position:{x:160,y:200}})
  await page.locator('.pl-live__side-actions').getByRole('button',{name:'フォロー',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.__hakuLiveQa.follows),1)
  await page.locator('.pl-live__stage').click({position:{x:160,y:200}})
  await page.getByRole('button',{name:'応援する',exact:true}).click()
  assert.equal(await page.evaluate(()=>document.body.dataset.tip),'opened')
  await page.evaluate(()=>window.__hakuLiveQa.end())
  await page.waitForFunction(()=>window.__hakuLiveQa.disconnects>=2)
  assert.equal(await page.getByRole('button',{name:'LIVEに再接続',exact:true}).count(),0)
  assert.deepEqual(errors,[])
  await page.goto('http://127.0.0.1:5189/tests/browser/haribow/index.html?host=1')
  await page.waitForFunction(()=>window.__hakuLiveQa.connects===1)
  await page.evaluate(()=>window.__hakuLiveQa.emit('reconnecting'))
  await page.getByRole('status').filter({hasText:'配信を再接続'}).waitFor()
  await page.evaluate(()=>window.__hakuLiveQa.emit('disconnected'))
  await page.getByRole('button',{name:'配信に再接続',exact:true}).click()
  await page.waitForFunction(()=>window.__hakuLiveQa.connects===2)
  await page.getByRole('button',{name:'配信に再接続',exact:true}).waitFor({state:'hidden'})
  assert.deepEqual(errors,[])
  results.push({browser:name,checks:['audio-user-gesture','reconnecting','manual-retry','follow','tip-navigation','end-disconnect','host-reconnecting','host-manual-retry'],kind:'MOCK UI ONLY'})
  await browser.close()
 }
 console.log(JSON.stringify(results,null,2))
})().catch(e=>{console.error(e);process.exit(1)})
