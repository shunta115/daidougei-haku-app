import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { webkit, devices } from 'playwright'
const output = process.env.HAKU_LIVE_QA_OUTPUT || '/private/tmp/haku-live-repair-evidence'
await mkdir(output,{recursive:true})
const results=[],errors=[]
const deadline=setTimeout(()=>{console.error('WebKit integration timeout');process.exit(1)},180_000)
const check=(name,pass)=>{assert.ok(pass,name);results.push(name);console.log('PASS',name)}
console.log('Launching isolated WebKit')
const browser=await webkit.launch({headless:true,timeout:30000})
try {
 console.log('Creating iPhone context')
 const context=await browser.newContext({...devices['iPhone 13'],locale:'ja-JP',timezoneId:'Asia/Tokyo'})
 await context.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort())
 await context.addInitScript(()=>{
  Object.defineProperty(navigator,'share',{configurable:true,value:async data=>{window.__shared=data}})
  Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async value=>{window.__copied=value}}})
 })
 console.log('Opening three isolated tabs')
 const a=await context.newPage(), b=await context.newPage(), host=await context.newPage()
 for(const page of [a,b,host])page.on('pageerror',error=>errors.push(error.message))
 const url='http://127.0.0.1:4187/tests/live-repair-e2e/harness.html'
 for(let i=0;i<80;i++){try{if((await fetch(url)).ok)break}catch{}await new Promise(r=>setTimeout(r,250))}
 console.log('Loading QA screens')
 await a.goto(url+'?actor=a');await b.goto(url+'?actor=b');await host.goto(url+'?host=1')
 await a.getByLabel('無料のいいねを送る',{exact:true}).first().waitFor()
 for(let i=0;i<3;i++)await a.getByLabel('無料のいいねを送る',{exact:true}).first().tap()
 await b.getByLabel('無料のいいねを送る',{exact:true}).first().tap()
 await host.getByText('LIVE累計 ♥ 4',{exact:true}).waitFor()
 check('two viewers send taps to host cumulative total',true)
 check('portrait FEVER leaves LIVE stats readable',await a.evaluate(()=>{const f=document.querySelector('.pl-fever').getBoundingClientRect(),s=document.querySelector('.pl-live__stats').getBoundingClientRect();return f.top>=s.bottom||f.bottom<=s.top||f.right<=s.left||f.left>=s.right}))
 check('host renders received heart animation',await host.locator('.pl-fever__hearts span').count()>0)
 await host.screenshot({path:output+'/host.png'})
 await a.getByLabel('シェア',{exact:true}).tap()
 check('share passes direct performer and session URL',await a.evaluate(()=>window.__shared.url.includes('watch=10000000')&&window.__shared.url.includes('liveStartedAt=')))
 await a.evaluate(()=>{Object.defineProperty(navigator,'share',{configurable:true,value:undefined})})
 await a.getByLabel('シェア',{exact:true}).tap()
 await a.getByRole('status').filter({hasText:'LIVEのURLをコピーしました。'}).waitFor()
 check('unsupported sharing copies URL and displays feedback',await a.evaluate(()=>window.__copied.includes('watch=')))
 await a.getByLabel('共有結果を閉じる').tap()
 await a.getByLabel('視聴設定',{exact:true}).tap()
 check('settings opens without cropping video',await a.getByRole('dialog',{name:'視聴設定',exact:true}).isVisible()&&await a.locator('video').evaluate(el=>getComputedStyle(el).objectFit)==='contain')
 await a.getByLabel('コメントを表示',{exact:true}).uncheck()
 check('comments can be hidden',await a.locator('.pl-live__comments-wrap').isHidden())
 await a.getByLabel('コメントを表示',{exact:true}).check()
 await a.getByRole('button',{name:'視聴設定を閉じる',exact:true}).tap()
 await a.getByLabel('音声をオフ',{exact:true}).tap()
 check('audio mute changes actual audio element',await a.locator('audio').evaluate(el=>el.muted))
 const input=a.locator('.pl-live__composer input')
 await input.fill('視聴者から相手へ届くコメント')
 await a.locator('.pl-live__composer button').tap()
 await b.getByText('視聴者から相手へ届くコメント',{exact:false}).waitFor()
 await host.getByText('視聴者から相手へ届くコメント',{exact:false}).waitFor()
 check('viewer comment appears on actual performer screen and another viewer over isolated browser channel',true)
 await a.evaluate(async()=>{const api=await import('/tests/live-repair-e2e/fixture-api.ts');for(let i=0;i<90;i++)await api.postLiveComment({userId:'a',displayName:'QA',body:'comment '+i})})
 await a.getByText('comment 89',{exact:false}).waitFor()
 check('80-comment cap still scrolls to newest entry',await a.locator('.pl-live__comments').evaluate(el=>el.scrollHeight-el.scrollTop-el.clientHeight<35))
 await a.screenshot({path:output+'/portrait.png'})
 await a.setViewportSize({width:844,height:390})
 await a.waitForTimeout(400)
 check('landscape separates video from comments',await a.evaluate(()=>{const v=document.querySelector('.pl-live__stage').getBoundingClientRect(),p=document.querySelector('.pl-live__panel').getBoundingClientRect();return v.right<=p.left+1&&p.right<=innerWidth+1}))
 await a.screenshot({path:output+'/landscape.png'})
 await a.getByLabel('プレーヤーを全画面表示',{exact:true}).tap()
 check('fullscreen leaves live actions reachable',await a.getByLabel('全画面表示を終了',{exact:true}).isVisible()&&await a.getByLabel('無料のいいねを送る',{exact:true}).first().isVisible())
 await a.getByLabel('全画面表示を終了',{exact:true}).tap()
 const old=await context.newPage();await old.goto(url+'?liveStartedAt=2026-10-30T00%3A00%3A00Z')
 await old.getByText('このLIVEは終了しました。',{exact:true}).waitFor()
 check('old shared session does not join a newer LIVE',await old.getByLabel('無料のいいねを送る',{exact:true}).first().isDisabled())
 check('no browser runtime errors',errors.length===0)
 await context.close()
} finally {
 await writeFile(output+'/result.json',JSON.stringify({browser:'WebKit desktop with iPhone 13 emulation',physicalIPhone:false,transport:'offline adapters; not Supabase or LiveKit',results,errors},null,2))
 clearTimeout(deadline)
 await browser.close()
}
